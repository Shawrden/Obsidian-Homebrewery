import esbuild from "esbuild";
import process from "node:process";
import { builtinModules } from "node:module";

const banner = `/*! @license
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Source: https://github.com/ (obsidian-homebrewery-exporter) — edit files in src/ instead.

Homebrew Exporter — layout and CSS conventions modeled after NaturalCrit's Homebrewery
(https://github.com/naturalcrit/homebrewery), MIT License.
Bundled fonts Cinzel, Libre Baskerville and Open Sans are licensed under the SIL Open Font License 1.1
(https://openfontlicense.org).
*/
`;

const production = process.argv[2] === "production";

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
    ...builtinModules.map((m) => `node:${m}`),
  ],
  format: "cjs",
  target: "es2018",
  loader: {
    ".woff2": "dataurl",
  },
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  minify: production,
  outfile: "main.js",
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}
